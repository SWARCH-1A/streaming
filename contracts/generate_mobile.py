#!/usr/bin/env python3
"""Deterministic Kotlin consumer models from the neutral contract sources (no network)."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "contracts/generated/mobile/MobileContracts.kt"
ROOTS = "P2NativeLogin LoginRequest RegistrationRequest Registration Profile ChannelBootstrap PublicStream PublicSession Taxonomy ChatMessage ChatHistory ViewerLease P2RecoveryRequest P2RecoveryAccepted P2RecoveryConfirm P2Vod P2VodPage P2Timeline P2SubtitlePage P2OperationStatus".split()


def generate():
    base = json.loads((ROOT / "contracts/p1.json").read_text())
    extra = json.loads((ROOT / "contracts/p2.json").read_text())
    schemas = base["schemas"] | extra["schemas"]
    needed = set()

    def kind(s):
        if "$ref" in s:
            name = s["$ref"].split("/")[-1]
            needed.add(name)
            return name
        if "anyOf" in s:
            items = [x for x in s["anyOf"] if x.get("type") != "null"]
            return kind(items[0]) + "?" if len(items) == 1 else "JsonElement"
        t = s.get("type")
        if isinstance(t, list):
            return kind(s | {"type": next(x for x in t if x != "null")}) + "?"
        if "enum" in s or "const" in s:
            value = s.get("const", s.get("enum", [""])[0])
            return "Boolean" if isinstance(value, bool) else "String" if isinstance(value, str) else "Long"
        if t == "array":
            return "List<" + kind(s["items"]) + ">"
        return {"integer": "Long", "number": "Double", "string": "String", "boolean": "Boolean"}.get(t, "JsonObject" if t == "object" else "JsonElement")

    pending = list(ROOTS)
    emitted = {}
    while pending:
        name = pending.pop()
        if name in emitted:
            continue
        s = schemas[name]
        fields = []
        for field, schema in s["properties"].items():
            kt = kind(schema)
            optional = field not in s.get("required", [])
            if optional and not kt.endswith("?"):
                kt += "?"
            fields.append(f"    val {field}: {kt}" + (" = null" if optional else ""))
        secret = any(x in s["properties"] for x in ["accessToken", "password", "newPassword", "recoveryToken", "leaseToken"])
        emitted[name] = "@Serializable\ndata class " + name + "(\n" + ",\n".join(fields) + "\n)" + (f' {{ override fun toString(): String = "{name}([redacted])" }}' if secret else "")
        pending.extend(needed - emitted.keys())
    queries = []
    for query in base["graphqlQueries"]:
        # A Kotlin raw string needs escaped interpolation markers.
        text = query["query"].replace("$", "${'$'}")
        queries.append('    const val ' + query["name"] + ' = """' + text + '"""')
    return "// Generated by contracts/generate_mobile.py; do not edit.\npackage streaming.mobile.contracts\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.json.*\n\n" + "\n\n".join(emitted[k] for k in sorted(emitted)) + "\n\nobject DiscoveryQueries {\n" + "\n".join(queries) + "\n}\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(output)
    elif not OUTPUT.exists() or OUTPUT.read_text() != output:
        raise SystemExit("Kotlin contracts drifted; run python3 contracts/generate_mobile.py --write")
    print("Mobile Kotlin contracts verified")
